"""Send representative FlashArray syslog lines to the purefa_syslog listener.

    python3 tests/syslog_send.py <host> <port> [udp|tcp] [array-name]

The first lines follow the layouts Purity//FA 6.10.6 sends (no PRI, a pid
on the program, the controller as hostname; a command record and a
session record for purity.audit, and purity.test), anonymised from a
capture. The rest follow the `Key: 'value'` layout Pure's SIEM partners
publish plus a purity.alert example; the alert text is representative,
not captured.
"""

import socket
import sys
import time

host = sys.argv[1] if len(sys.argv) > 1 else "127.0.0.1"
port = int(sys.argv[2]) if len(sys.argv) > 2 else 5140
proto = sys.argv[3] if len(sys.argv) > 3 else "udp"
array = sys.argv[4] if len(sys.argv) > 4 else "array-a"
stamp = time.strftime("%b %d %H:%M:%S")
utc = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
lines = [
    f"{stamp} {array}-ct1 purity.audit[211234]: [eda-human (local)]@{array}(6d9a1ac1-0000-4000-8000-000000000001) "
    f"purevol destroy  eda-syslog-human. Message ID: 158643935 UTC Time: {utc} Array Name: {array}",
    f"{stamp} {array}-ct1 purity.audit[211234]: (login message ID: 158643943) Array name: '{array}' Controller: 1 "
    f"Interface: 'REST' Module: '' Session: '7b292a96-0000-4000-8000-000000000002' UTC Time: {utc} User: 'eda-human' "
    f"Location: '203.0.113.9' Sublocation: 'Python-urllib/3.9' Action: 'session request' Method: 'api_token' "
    f"Result: Success Description: ''",
    f"{stamp} {array}-ct1 purity.test[73629]: INFO [pure_middleware] This is a test message generated by Pure Storage "
    f"FlashArray. UTC Time: {utc} Array Name: {array}",
    f"<182>{stamp} {array} purity.audit: (login message ID: 676886) Array name: '{array}' Controller: 0 Interface: 'REST' "
    f"Module: '' Session: 'abc123' UTC Time: {utc} User: 'eda-human' Location '203.0.113.9' Sublocation: 'python-requests/2.32' "
    f"Action: 'login' Method: '' Result: Success Description: ''",
    f"<182>{stamp} {array} purity.audit: (operation message ID: 676887) Array name: '{array}' Controller: 0 Interface: 'CLI' "
    f"Module: 'purevol' Session: 'abc124' UTC Time: {utc} User: 'eda-human' Location '203.0.113.9' Sublocation: 'ssh' "
    f"Action: 'purevol destroy prod-vol' Method: '' Result: Success Description: 'volume destroyed'",
    f"<180>{stamp} {array} purity.alert: (hardware:ct0.eth7): failure [code 42, severity warning]",
    f"<182>{stamp} {array} purity.test: This is a test message from {array}",
]
if proto == "tcp":
    s = socket.create_connection((host, port))
    for line in lines:
        s.sendall((line + "\n").encode())
    s.close()
else:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    for line in lines:
        s.sendto(line.encode(), (host, port))
    s.close()
print(f"sent {len(lines)} lines to {host}:{port}/{proto}")
